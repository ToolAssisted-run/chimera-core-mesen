#!/usr/bin/env python3
"""Writes a C++ file holding Mesen's NES game database as one byte array.

Usage: embed-db.py <MesenNesDB.txt> <out.cpp>

Mesen's UI ships the database beside the program and the core reads it from
its home folder. A core has no folder of its own, so the text is compiled in
and handed to GameDatabase::LoadGameDb before a game is loaded.
"""
import sys

data = open(sys.argv[1], "rb").read()
with open(sys.argv[2], "w") as f:
    f.write("/* generated by waterbox/embed-db.py from MesenNesDB.txt - do not edit */\n")
    f.write("#include <cstddef>\n")
    f.write('extern "C" const char mesen_nes_db[] = {\n')
    for i in range(0, len(data), 24):
        f.write(",".join(str(b) for b in data[i:i + 24]) + ",\n")
    f.write("0};\n")
    f.write('extern "C" const size_t mesen_nes_db_size = %d;\n' % len(data))
